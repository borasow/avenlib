import assert from "node:assert";
import { readFileSync } from "node:fs";
import ts from "typescript";
const src = readFileSync(new URL("./calculs.ts", import.meta.url), "utf8");
const js = ts.transpileModule(src, { compilerOptions: { module: "ESNext", target: "ES2020" } }).outputText;
const m = await import("data:text/javascript;base64," + Buffer.from(js).toString("base64"));
assert.equal(m.impotRevenu(11600, 1, false), 0);
assert.equal(m.impotRevenu(29579, 1, false), Math.round((29579 - 11600) * 0.11));
assert.equal(m.impotRevenu(50000, 2, true), Math.round(m.bareme(25000) * 2));
const n = m.netMicro({ regime: "service", ca: 50000, charges: 0, parts: 1, couple: false, autresRevenus: 0, versementLiberatoire: false });
assert.equal(n.cotisations, Math.round(50000 * 0.215)); assert.ok(n.netApresImpot < 50000 * 0.785);
const vl = m.netMicro({ regime: "vente", ca: 10000, charges: 0, parts: 1, couple: false, autresRevenus: 0, versementLiberatoire: true });
assert.equal(vl.impot, 100);
const t = m.calculerTjm({ netMensuelVoulu: 3000, chargesMensuelles: 300, regime: "bnc", congesJours: 25, maladieJours: 5, pctNonFacture: 20 });
assert.ok(t.tjm > 250 && t.tjm < 400, String(t.tjm));
assert.equal(m.matelas(6000, 2000, 500).moisTenus, 3);
assert.equal(m.matelas(6000, 2000, 500).moisPourAtteindre, 12);
const r = m.retraiteSsi(40000, 100, 20); assert.equal(r.trimestres, 172); assert.equal(r.base, Math.round(40000 * 0.5));
const e = m.capaciteEmprunt({ revenuMensuel: 4000, creditsEnCours: 0, tauxAnnuel: 3.5, assuranceAnnuelle: 0, dureeAns: 20, apport: 20000 });
assert.equal(e.mensualiteMax, 1400); assert.ok(e.capital > 240000 && e.capital < 250000, String(e.capital));
const p = m.prevoyance(50, true, 3000, 30); assert.equal(p.manqueMensuel, 1500);
console.log("calculs ok");
